  var CLASSIC_HEIGHT_MULTS = {
    egg: 1.3, baby: 1.0, child: 1.0, teen: 1.35, adult: 1.5, senior: 1.4
  };

  /** Classic is an upright type — the same petSize multipliers as the upright grids. */
  function classicSizeMultiplier() {
    var ps = (typeof document !== "undefined" && document.body && document.body.dataset)
           ? (document.body.dataset.petSize || "medium") : "medium";
    return ps === "small" ? 0.5625 : ps === "large" ? 1.0 : 0.75;
  }

  /**
   * True when renderSpriteGrid draws this pet as the procedural classic creature:
   * classic itself, or a species with no grid for this stage or its adult (BUG-S03).
   */
  function drawsAsClassic(spriteType, stage) {
    spriteType = spriteType || "classic";
    if (spriteType === "classic") { return true; }
    var g = SPRITES[spriteType];
    return !(g && (g[stage || "baby"] || g["adult"]));
  }

  /**
   * The classic creature's real drawn size: { w, h } with the feet at y + h.
   * The sidebar uses this as classic's bounding box, so the (x, bodyY) passed to
   * renderSpriteGrid is the top-left of the creature itself, not of a 32×48 grid.
   */
  function classicBox(state, STAGE_SCALES, weightWidthMultiplier, sizeMultiplier) {
    STAGE_SCALES          = STAGE_SCALES || window.SPRITE_STAGE_SCALES;
    weightWidthMultiplier = weightWidthMultiplier || window.spriteWeightWidthMult;
    if (sizeMultiplier === undefined) { sizeMultiplier = classicSizeMultiplier(); }
    var stage      = state.stage || "baby";
    // Classic keeps the original v0.11.2 base size of 24 — this is the authentic
    // legacy look. Do not change to 96 (that applies to grid-based upright sprites).
    var bodySize   = Math.round(24 * (STAGE_SCALES[stage] || 0.5) * sizeMultiplier);
    var bodyWidth  = Math.round(bodySize * weightWidthMultiplier(state.weight || 50));
    var bodyHeight = Math.round(bodySize * (CLASSIC_HEIGHT_MULTS[stage] || 1.0));
    var legH       = Math.max(2, Math.round(bodySize * 0.22));
    // Longest leg drawn for the stage (the other leg is 1px shorter on alternate frames)
    var groundLegH = stage === "egg"    ? 0
                   : stage === "baby"   ? Math.max(1, Math.round(bodySize * 0.12))
                   : stage === "senior" ? Math.max(2, Math.round(bodySize * 0.25))
                   : stage === "child"  ? legH
                   : Math.max(2, Math.round(bodySize * 0.30)); // teen / adult
    return { w: bodyWidth, h: bodyHeight + groundLegH,
             bodySize: bodySize, bodyWidth: bodyWidth, bodyHeight: bodyHeight, legH: legH };
  }

  function drawClassicProcedural(ctx, state, x, bodyY, facingLeft, legFrame,
                                 breathPhase, STAGE_SCALES, weightWidthMultiplier,
                                 sizeMultiplier) {
    var primary   = "#39ff14";
    var secondary = state.sick ? "#ff4444" : (state.sleeping ? "#888888" : "#ff00ff");

    var stage = state.stage || "baby";

    // (x, bodyY) is the top-left of classicBox — the creature's own bounding box
    var box        = classicBox(state, STAGE_SCALES, weightWidthMultiplier, sizeMultiplier);
    var bodySize   = box.bodySize;
    var bodyWidth  = box.bodyWidth;
    var bodyHeight = box.bodyHeight;
    var legH       = box.legH;

    // Sleeping breath bob
    var bobY = bodyY;
    if (state.sleeping) {
      bobY = bodyY + Math.round(Math.sin(breathPhase) * 1);
    }

    ctx.save();
    if (facingLeft) {
      ctx.translate(x + bodyWidth, 0);
      ctx.scale(-1, 1);
      ctx.translate(-x, 0);
    }

    if (stage === "egg") {
      drawHatchingEgg(ctx, state, x, bobY, bodyWidth, bodyHeight, bodySize, primary, secondary);

    } else if (stage === "baby") {
      var babyLegH = Math.max(1, Math.round(bodySize * 0.12));
      var legW  = Math.max(2, Math.round(bodyWidth * 0.15));
      var legX1 = x + Math.round(bodyWidth * 0.2);
      var legX2 = x + Math.round(bodyWidth * 0.6);
      var legY  = bobY + bodyHeight;
      ctx.fillStyle = primary;
      ctx.fillRect(legX1, legY, legW, legFrame === 0 ? babyLegH     : babyLegH - 1);
      ctx.fillRect(legX2, legY, legW, legFrame === 0 ? babyLegH - 1 : babyLegH    );

      ctx.fillStyle = primary;
      ctx.fillRect(x, bobY, bodyWidth, bodyHeight);

      var eyeSize   = Math.max(2, Math.round(bodySize * 0.30));
      var eyeY      = bobY + Math.round(bodyHeight * 0.20);
      var leftEyeX  = x + Math.round(bodyWidth * 0.10);
      var rightEyeX = x + Math.round(bodyWidth * 0.55);
      ctx.fillStyle = secondary;
      ctx.fillRect(leftEyeX,  eyeY, eyeSize, eyeSize);
      ctx.fillRect(rightEyeX, eyeY, eyeSize, eyeSize);

      var mouthY = bobY + Math.round(bodyHeight * 0.72);
      var mouthX = x + Math.round(bodyWidth * 0.3);
      var mouthW = Math.round(bodyWidth * 0.4);
      ctx.fillStyle = secondary;
      if (state.mood === "happy") {
        ctx.fillRect(mouthX,              mouthY,     2, 2);
        ctx.fillRect(mouthX + mouthW - 2, mouthY,     2, 2);
        ctx.fillRect(mouthX + 2,          mouthY + 2, mouthW - 4, 2);
      } else if (state.mood === "sad" || state.sick) {
        ctx.fillRect(mouthX,              mouthY + 2, 2, 2);
        ctx.fillRect(mouthX + mouthW - 2, mouthY + 2, 2, 2);
        ctx.fillRect(mouthX + 2,          mouthY,     mouthW - 4, 2);
      } else {
        ctx.fillRect(mouthX, mouthY + 1, mouthW, 2);
      }

    } else if (stage === "child") {
      var legWc  = Math.max(2, Math.round(bodyWidth * 0.15));
      var legX1c = x + Math.round(bodyWidth * 0.2);
      var legX2c = x + Math.round(bodyWidth * 0.6);
      var legYc  = bobY + bodyHeight;
      ctx.fillStyle = primary;
      ctx.fillRect(legX1c, legYc, legWc, legFrame === 0 ? legH     : legH - 1);
      ctx.fillRect(legX2c, legYc, legWc, legFrame === 0 ? legH - 1 : legH    );

      ctx.fillStyle = primary;
      ctx.fillRect(x, bobY, bodyWidth, bodyHeight);

      var eyeSizeC  = Math.max(2, Math.round(bodySize * 0.18));
      var eyeYC     = bobY + Math.round(bodyHeight * 0.25);
      var leftEyeXC  = x + Math.round(bodyWidth * 0.20);
      var rightEyeXC = x + Math.round(bodyWidth * 0.62);
      ctx.fillStyle = secondary;
      ctx.fillRect(leftEyeXC,  eyeYC, eyeSizeC, eyeSizeC);
      ctx.fillRect(rightEyeXC, eyeYC, eyeSizeC, eyeSizeC);

      var mouthYC = bobY + Math.round(bodyHeight * 0.65);
      var mouthXC = x + Math.round(bodyWidth * 0.3);
      var mouthWC = Math.round(bodyWidth * 0.4);
      ctx.fillStyle = secondary;
      if (state.mood === "happy") {
        ctx.fillRect(mouthXC,               mouthYC,     2, 2);
        ctx.fillRect(mouthXC + mouthWC - 2, mouthYC,     2, 2);
        ctx.fillRect(mouthXC + 2,           mouthYC + 2, mouthWC - 4, 2);
      } else if (state.mood === "sad" || state.sick) {
        ctx.fillRect(mouthXC,               mouthYC + 2, 2, 2);
        ctx.fillRect(mouthXC + mouthWC - 2, mouthYC + 2, 2, 2);
        ctx.fillRect(mouthXC + 2,           mouthYC,     mouthWC - 4, 2);
      } else {
        ctx.fillRect(mouthXC, mouthYC + 1, mouthWC, 2);
      }

    } else {
      // teen / adult / senior
      var bigLegH    = Math.max(2, Math.round(bodySize * 0.30));
      var seniorLegH = Math.max(2, Math.round(bodySize * 0.25));
      var actualLegH = stage === "senior" ? seniorLegH : bigLegH;

      var legWT  = Math.max(2, Math.round(bodyWidth * 0.15));
      var legX1T = x + Math.round(bodyWidth * 0.2);
      var legX2T = x + Math.round(bodyWidth * 0.6);
      var legYT  = bobY + bodyHeight;
      ctx.fillStyle = primary;
      ctx.fillRect(legX1T, legYT, legWT, legFrame === 0 ? actualLegH     : actualLegH - 1);
      ctx.fillRect(legX2T, legYT, legWT, legFrame === 0 ? actualLegH - 1 : actualLegH    );

      var headFrac        = stage === "teen" ? 0.40 : (stage === "senior" ? 0.42 : 0.38);
      var headH           = Math.round(bodyHeight * headFrac);
      var torsoH          = bodyHeight - headH;
      var torsoYBase      = bobY + headH;
      var torsoWidthFrac  = stage === "teen" ? 0.82 : (stage === "senior" ? 0.90 : 1.0);
      var torsoWidth      = Math.round(bodyWidth * torsoWidthFrac);
      var torsoX          = x + Math.round((bodyWidth - torsoWidth) / 2);

      ctx.fillStyle = primary;
      ctx.fillRect(torsoX, torsoYBase, torsoWidth, torsoH);

      if (stage === "adult") {
        ctx.fillRect(torsoX - 2, torsoYBase, 2, 4);
        ctx.fillRect(torsoX + torsoWidth, torsoYBase, 2, 4);
      }

      ctx.fillStyle = primary;
      ctx.fillRect(x, bobY, bodyWidth, headH);

      var eyeSizeT  = Math.max(2, Math.round(bodySize * 0.18));
      var eyeYT     = bobY + Math.round(headH * 0.35);
      var leftEyeXT  = x + Math.round(bodyWidth * 0.20);
      var rightEyeXT = x + Math.round(bodyWidth * 0.62);
      ctx.fillStyle = secondary;
      ctx.fillRect(leftEyeXT,  eyeYT, eyeSizeT, eyeSizeT);
      ctx.fillRect(rightEyeXT, eyeYT, eyeSizeT, eyeSizeT);

      var mouthYT = bobY + Math.round(headH * 0.72);
      var mouthXT = x + Math.round(bodyWidth * 0.3);
      var mouthWT = Math.round(bodyWidth * 0.4);
      ctx.fillStyle = secondary;
      if (state.mood === "happy") {
        ctx.fillRect(mouthXT,               mouthYT,     2, 2);
        ctx.fillRect(mouthXT + mouthWT - 2, mouthYT,     2, 2);
        ctx.fillRect(mouthXT + 2,           mouthYT + 2, mouthWT - 4, 2);
      } else if (state.mood === "sad" || state.sick) {
        ctx.fillRect(mouthXT,               mouthYT + 2, 2, 2);
        ctx.fillRect(mouthXT + mouthWT - 2, mouthYT + 2, 2, 2);
        ctx.fillRect(mouthXT + 2,           mouthYT,     mouthWT - 4, 2);
      } else {
        ctx.fillRect(mouthXT, mouthYT + 1, mouthWT, 2);
      }
    }

    ctx.restore();
  }


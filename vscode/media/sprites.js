  /**
   * Renders the pixel-art grid for the given state at (x, bodyY).
   *
   * Grid sizes:
   *   Upright (monkey, rooster, dragon) : 32 cols x 48 rows
   *   Quadruped + Snake (all others)              : 48 cols x 32 rows
   *
   * Leg rows:
   *   Upright   : rows >= 37
   *   Quadruped : rows >= 25
   *   Snake     : none (all leg rows are blank)
   *
   * @param {CanvasRenderingContext2D} ctx
   * @param {object}  state
   * @param {number}  x           - left edge of bounding box
   * @param {number}  bodyY       - top of bounding box
   * @param {boolean} facingLeft
   * @param {number}  legFrame    - 0 or 1
   * @param {number}  breathPhase - sleeping breath phase (radians)
   * @param {object}  STAGE_SCALES
   * @param {Function} weightWidthMultiplier
   * @param {Function} getPalette
   * @param {Function} spriteHeightRatio - returns height/width ratio for a spriteType
   * @param {Function} quadrupedBellySagRows - returns extra belly-sag row count for overweight quadrupeds
   */
  // ── Sprite raster cache ──────────────────────────────────────────────────
  // Caches pre-painted offscreen canvases for the high-res imported path so
  // renderSpriteGrid never repaints a full grid unless the visual state changes.
  // Also caches sparse pixel data per (spriteType|stage) to avoid full-grid
  // scans even when a cache miss requires a repaint.
  //
  // LRU bound: max 64 entries; oldest entry evicted when limit is reached.
  var _rasterCache = [];   // array of { key, canvas }  — LRU order (0=oldest)
  var _rasterMap   = {};   // key → index into _rasterCache for O(1) lookup
  var RASTER_MAX   = 64;

  // Sparse pixel data: per (spriteType|stage), stores array of
  // { row, col, cell } for non-zero cells only.  Built once on first use.
  var _sparseCache = {};   // "spriteType|stage" → Array<{row,col,cell}>

  function _getSparse(spriteType, stage, grid, ROWS, COLS) {
    var sparseKey = spriteType + "|" + stage;
    if (_sparseCache[sparseKey]) { return _sparseCache[sparseKey]; }
    var sparse = [];
    for (var r = 0; r < ROWS; r++) {
      if (!grid[r]) { continue; }
      for (var c = 0; c < COLS; c++) {
        var v = grid[r][c];
        if (v) { sparse.push(r, c, v); }  // flat triplet array — fewer objects
      }
    }
    _sparseCache[sparseKey] = sparse;
    return sparse;
  }

  function _getRaster(cacheKey, COLS, ofcH) {
    var idx = _rasterMap[cacheKey];
    if (idx !== undefined) {
      // Move to end (most-recently-used).
      var entry = _rasterCache.splice(idx, 1)[0];
      _rasterCache.push(entry);
      // Rebuild index map.
      for (var i = 0; i < _rasterCache.length; i++) { _rasterMap[_rasterCache[i].key] = i; }
      return entry.canvas;
    }
    // Miss — evict oldest if at capacity.
    if (_rasterCache.length >= RASTER_MAX) {
      var evicted = _rasterCache.shift();
      delete _rasterMap[evicted.key];
      for (var j = 0; j < _rasterCache.length; j++) { _rasterMap[_rasterCache[j].key] = j; }
    }
    // Allocate new offscreen canvas.
    var ofc = document.createElement('canvas');
    ofc.width  = COLS;
    ofc.height = ofcH;
    _rasterCache.push({ key: cacheKey, canvas: ofc });
    _rasterMap[cacheKey] = _rasterCache.length - 1;
    return null;  // null signals caller to paint the canvas
  }

  function renderSpriteGrid(ctx, state, x, bodyY, facingLeft, legFrame, breathPhase,
                            STAGE_SCALES, weightWidthMultiplier, getPalette, spriteHeightRatio,
                            quadrupedBellySagRows) {

    var spriteType = state.spriteType || "classic";
    var stage      = state.stage      || "baby";

    // -- Missing sprite data (BUG-S03): a species with no grid for this stage
    // uses its adult grid (see the grid lookup below); a species with no adult
    // grid either (e.g. the archived zodiac animals) is drawn as the procedural
    // classic creature, so a pet is never invisible.
    if (drawsAsClassic(spriteType, stage)) {
      spriteType = "classic";
    }

    // -- Classic: legacy procedural renderer (v0.11.2 style, fixed neon green)
    if (spriteType === "classic") {
      drawClassicProcedural(ctx, state, x, bodyY, facingLeft, legFrame, breathPhase,
                            STAGE_SCALES, weightWidthMultiplier, classicSizeMultiplier());
      return;
    }

    var palette    = getPalette(state.spriteType);
    var primary    = palette.primary;
    var secondary  = palette.secondary;

    // -- Use the animal's own accent colour (index 3 = stripes, ridges, markings)
    // Falls back to darkened primary for any palette that lacks an explicit accent.
    function darkenHex(hex, factor) {
      var h = hex.replace("#", "");
      if (h.length === 3) { h = h[0]+h[0]+h[1]+h[1]+h[2]+h[2]; }
      var r = Math.round(parseInt(h.substring(0,2),16) * factor);
      var g = Math.round(parseInt(h.substring(2,4),16) * factor);
      var b = Math.round(parseInt(h.substring(4,6),16) * factor);
      return "rgb(" + r + "," + g + "," + b + ")";
    }

    var accent = palette.accent || darkenHex(primary, 0.70);

    // -- Sick / sleeping colour overrides ------------------------------------
    if (state.sick)     { secondary = "#ff4444"; }
    if (state.sleeping) { secondary = "#888888"; }

    // -- petSize multiplier --------------------------------------------------
    var petSizeVal = (typeof document !== "undefined" && document.body && document.body.dataset)
                   ? (document.body.dataset.petSize || "medium")
                   : "medium";
     // sizeMultiplier is assigned after isUpright is known (see below)
    var sizeMultiplier;

    // -- Determine grid type -------------------------------------------------
    // UPRIGHT_TYPES is authoritative in spriteConstants.js (loaded first).
    var isUpright = !!(window.UPRIGHT_TYPES && window.UPRIGHT_TYPES[spriteType]);

    // Upright animals render at smaller sizes than quadrupeds.
    // small=0.5625 / medium=0.75 / large=1.0 for upright;
    // small=0.75  / medium=1.0  / large=1.5  for quadruped (unchanged).
    sizeMultiplier = isUpright
      ? (petSizeVal === "small" ? 0.5625 : petSizeVal === "large" ? 1.0  : 0.75)
      : (petSizeVal === "small" ? 0.75   : petSizeVal === "large" ? 1.5  : 1.0);

    // Bug fix #1: correct COLS/ROWS and legRowStart per grid type
    // v2: read from SPRITE_GRID_META for variable-grid support; fall back to
    // legacy hardcoded values so existing sprites are unaffected.
    var _gridMeta   = (window.SPRITE_GRID_META && window.SPRITE_GRID_META[spriteType])
                    || (isUpright ? { cols: 32, rows: 48, legRowStart: 37 }
                                  : { cols: 48, rows: 32, legRowStart: 25 });
    var COLS        = _gridMeta.cols;
    var ROWS        = _gridMeta.rows;
    var legRowStart = _gridMeta.legRowStart;

    // -- Body dimensions ------------------------------------------------------
    var stageScale  = STAGE_SCALES[stage] || 0.65;

    // Bug fix #4: BASE_SIZE is 96 (was 24)
    var baseSize    = 96;
    var bodySize    = Math.round(baseSize * sizeMultiplier * stageScale);
    var wt          = state.weight || 50;

     // Overweight visual treatment:
     //   • All sprites: CSS blur applied to canvas element based on weight (in sidebar.js).
     //   • Quadrupeds (non-upright, non-snake): extra belly-sag rows inserted between
     //     body and legs via quadrupedBellySagRows(). Upright sprites and snake keep
     //     normal proportions — blur is the only visual cue for them.
     //   • Width stretch (weightWidthMultiplier) is no longer used.
     var isSnake   = (spriteType === "snake");
     var useWidthStretch = false;
     var wwm       = 1.0;
     var sagRows   = (!isUpright && !isSnake && stage !== "egg") ? quadrupedBellySagRows(wt) : 0;

    var bodyWidth   = Math.round(bodySize * wwm);
    // Compute bodyHeight so cells are square: height/width = ROWS/COLS.
    // This matches the ASCII sketch proportions exactly regardless of orientation.
    var bodyHeight  = Math.round(bodyWidth * spriteHeightRatio(spriteType));

    // Sleeping breath bob
    var bobY = bodyY;
    if (state.sleeping) {
      bobY = bodyY + Math.round(Math.sin(breathPhase) * 2);
    }

    // -- Egg: procedural rocking oval ----------------------------------------
    if (stage === "egg") {
      // Always a portrait oval (taller than wide), ignoring pet weight
      bodyWidth = bodySize;
      drawHatchingEgg(ctx, state, x, bobY, bodyWidth, bodyHeight, bodySize, primary, secondary);
      return;
    }

    // -- Grid lookup ---------------------------------------------------------
    var grid = SPRITES[spriteType][stage] || SPRITES[spriteType]["adult"];
    // Optional per-mood art (e.g. DEFS.dog.adult_sleeping) replaces the stage
    // grid; its key also keeps the raster and sparse caches apart.
    var gridKey = moodGridKey(SPRITES[spriteType], stage, state.displayMood || state.mood) || stage;
    if (gridKey !== stage) { grid = SPRITES[spriteType][gridKey]; }

    if (!grid) { return; }

    // Map colour index to actual colour
    // Index 4 = gold pearl (used by dragon sprite for the flaming pearl)
    // Index 5 = gold (used by monkey sprite for banana) — same colour
    var colorMap = {
      1: primary,
      2: secondary,
      3: accent,
      4: "#FFD700",
      5: "#FFD700"
    };

    // Monkey is an upright type but faces sideways (like a quadruped) —
    // flip it when NOT facing left, same as quadrupeds.
    var SIDE_FACING_UPRIGHT = { monkey: 1, rooster: 1 };
    var isSideUpright = !!SIDE_FACING_UPRIGHT[spriteType];

    ctx.save();
    if (isSideUpright ? !facingLeft : (isUpright ? facingLeft : !facingLeft)) {
      ctx.translate(x + bodyWidth / 2, 0);
      ctx.scale(-1, 1);
      ctx.translate(-(x + bodyWidth / 2), 0);
    }

    var cellWExact = bodyWidth  / COLS;
    var cellHExact = bodyHeight / ROWS;

    if (cellWExact >= 1) {
      // ── STANDARD PATH (all existing sprites) ────────────────────────────────
      // Each grid cell maps to at least 1 screen pixel.  Render with fillRect.
      var cellW = Math.max(1, Math.round(cellWExact));
      var cellH = Math.max(1, Math.round(cellHExact));

      // Bottom-align: shift the grid down so its last row lands at bodyY+bodyHeight.
      // Without this, rounding means ROWS*cellH < bodyHeight for small stages, making
      // the sprite float above the floor instead of standing on it.
      var gridBottomAlign = bodyHeight - ROWS * cellH;
      // Centre horizontally: split the rounding leftover (COLS*cellW vs bodyWidth)
      // evenly, so the sprite sits on the box centre and the mirror axis.
      var gx = x + Math.round((bodyWidth - COLS * cellW) / 2);

      // Belly-sag extra pixels: legs shift down by this amount so the sag fills the gap.
      var sagPixels = sagRows * cellH;

      for (var row = 0; row < ROWS; row++) {
        if (!grid[row]) { continue; }
        var isLegRow = (row >= legRowStart);

        for (var col = 0; col < COLS; col++) {
          var cell = grid[row][col];
          if (!cell) { continue; }

          var colOffsetY = 0;
          if (isLegRow) {
            // Leg rows shift down by sagPixels so the belly sag fills the gap above.
            colOffsetY = sagPixels;
            var halfCols  = COLS / 2;
            var isLeftLeg = col < halfCols;
            if (legFrame === -1) {
              // -1 = upright/neutral: both legs flush, no per-leg offset
            } else if (legFrame === 0) {
              colOffsetY += isLeftLeg ? 0 : cellH;
            } else {
              colOffsetY += isLeftLeg ? cellH : 0;
            }
          }

          ctx.fillStyle = colorMap[cell] || primary;
          ctx.fillRect(
            gx + col * cellW,
            bobY + gridBottomAlign + row * cellH + colOffsetY,
            cellW,
            cellH
          );
        }
      }

      // -- Belly-sag rows (quadruped overweight only) ---------------------------
      // Draw procedural rows between body bottom (row legRowStart-1) and the
      // now-shifted legs.  Each sag row copies the silhouette of the last body row
      // (row legRowStart-1 = row 24), inset by one extra column on each side per
      // sag row, giving a tapered hanging-belly shape filled with the primary colour.
      if (sagRows > 0 && grid[legRowStart - 1]) {
        var bodyBottomRow = grid[legRowStart - 1];
        // Determine the leftmost and rightmost non-zero column of the body bottom row.
        var silLeft  = COLS;
        var silRight = -1;
        for (var bc = 0; bc < COLS; bc++) {
          if (bodyBottomRow[bc]) {
            if (bc < silLeft)  { silLeft  = bc; }
            if (bc > silRight) { silRight = bc; }
          }
        }
        ctx.fillStyle = primary;
        for (var s = 0; s < sagRows; s++) {
          // Inset by (s+1) columns on each side — sag narrows toward the bottom.
          var inset    = s + 1;
          var sagLeft  = silLeft  + inset;
          var sagRight = silRight - inset;
          if (sagLeft >= sagRight) { continue; }  // inset has closed off — skip
          var sagY = bobY + gridBottomAlign + legRowStart * cellH + s * cellH;
          ctx.fillRect(
            gx + sagLeft  * cellW,
            sagY,
            (sagRight - sagLeft + 1) * cellW,
            cellH
          );
        }
      }

    } else {
      // ── V2 OFFSCREEN PATH (high-res imported sprites) — CACHED ───────────────
      // cellWExact < 1: grid is larger than the on-screen bounding box.
      // Render full grid at 1 px/cell on an offscreen canvas, then scale-blit.
      // The offscreen canvas is cached by visual state so it is painted at most
      // once per unique combination of (spriteType, stage, legFrame, sagRows,
      // palette colours).  Subsequent frames reuse the cached canvas via drawImage
      // only — no loops, no allocations.

      var ofcH = ROWS + sagRows;
      var rasterKey = spriteType + "|" + gridKey + "|" + legFrame + "|" + sagRows +
                      "|" + primary + "|" + secondary + "|" + accent;
      var ofc = null;
      var cachedCanvas = _getRaster(rasterKey, COLS, ofcH);

      if (cachedCanvas) {
        // Cache hit — reuse existing painted canvas.
        ofc = cachedCanvas;
      } else {
        // Cache miss — retrieve the newly allocated (blank) canvas and paint it.
        ofc = _rasterCache[_rasterCache.length - 1].canvas;
        var ofcCtx = ofc.getContext('2d');
        ofcCtx.clearRect(0, 0, COLS, ofcH);

        // Use sparse pixel list to avoid scanning all ROWS*COLS every paint.
        var sparse = _getSparse(spriteType, gridKey, grid, ROWS, COLS);
        var oHalfCols = COLS / 2;
        for (var si = 0, slen = sparse.length; si < slen; si += 3) {
          var oRow  = sparse[si];
          var oCol  = sparse[si + 1];
          var oCell = sparse[si + 2];

          var oDrawRow = oRow;
          var oIsLegRow = (oRow >= legRowStart);
          if (oIsLegRow) {
            oDrawRow += sagRows;
            var oIsLeftLeg = oCol < oHalfCols;
            if (legFrame === 0) {
              oDrawRow += oIsLeftLeg ? 0 : 1;
            } else if (legFrame === 1) {
              oDrawRow += oIsLeftLeg ? 1 : 0;
            }
            // legFrame === -1: upright/neutral — no per-leg offset
          }

          ofcCtx.fillStyle = colorMap[oCell] || primary;
          ofcCtx.fillRect(oCol, oDrawRow, 1, 1);
        }

        // Belly-sag procedural rows (same logic as standard path).
        if (sagRows > 0 && grid[legRowStart - 1]) {
          var oBodyBottomRow = grid[legRowStart - 1];
          var oSilLeft  = COLS;
          var oSilRight = -1;
          // Use sparse scan of just the bottom body row.
          var sagSparse = _getSparse(spriteType, gridKey, grid, ROWS, COLS);
          for (var ss = 0, sslen = sagSparse.length; ss < sslen; ss += 3) {
            if (sagSparse[ss] === legRowStart - 1) {
              var bc = sagSparse[ss + 1];
              if (bc < oSilLeft)  { oSilLeft  = bc; }
              if (bc > oSilRight) { oSilRight = bc; }
            }
          }
          if (oSilRight >= oSilLeft) {
            ofcCtx.fillStyle = primary;
            for (var os = 0; os < sagRows; os++) {
              var oInset    = os + 1;
              var oSagLeft  = oSilLeft  + oInset;
              var oSagRight = oSilRight - oInset;
              if (oSagLeft >= oSagRight) { continue; }
              ofcCtx.fillRect(oSagLeft, legRowStart + os, oSagRight - oSagLeft + 1, 1);
            }
          }
        }
      }

      // Scale-blit cached offscreen canvas to main canvas.
      // imageSmoothingEnabled = false keeps pixel-art crispness.
      var oGridBottomAlign = bodyHeight - Math.round(bodyHeight);
      ctx.imageSmoothingEnabled = false;
      ctx.drawImage(
        ofc,
        x,
        bobY + oGridBottomAlign,
        bodyWidth,
        bodyHeight + sagRows * Math.round(bodyHeight / ROWS)
      );
    }

    ctx.restore();
  }

  // =========================================================================
  // Mood layer — props, body motion and particles drawn around the pet
  // (FEATURES_2.md §3.1). The sprite pixels themselves are never changed;
  // real per-mood art can be added as DEFS[type][stage + "_" + mood] and is
  // picked up by the grid lookup in renderSpriteGrid.
  // =========================================================================

  var MOOD_FRAMES = {        // flip-book length and ticks per frame (60 ticks ≈ 1 s)
    sleeping: { n: 2, ticks: 45 },
    eating:   { n: 3, ticks: 8 },    // fast chomp
  };
  // Happy and sad play only in short bursts: frame 0 (nothing) most of the
  // time, then frames 1, 2, 1, … for `len` ticks once every `every` ticks.
  // `offset` sets when the first burst comes after the pet is first drawn.
  var MOOD_BURSTS = {
    happy: { every: 1800, len: 60, ticks: 15, offset: 600 },   // ~1 s every ~30 s, first after ~20 s
    sad:   { every: 1800, len: 90, ticks: 30, offset: 1200 },  // ~1.5 s every ~30 s, first after ~10 s
  };
  var MOOD_PARTICLE_MAX = 20;
  var MOOD_GRAVITY      = 120;       // px/s² for tears and crumbs

  /**
   * Mood shown by the webview: "eating" while a feed reaction or a floor-snack
   * chomp is playing, else happy / sad / sleeping from state.mood. Neutral and
   * sick have no mood layer (sick keeps its own crawl and "+" indicator).
   */
  function currentMood(state, reactionType, chomping) {
    if (!state || !state.alive || state.stage === "egg") { return null; }
    if (state.sleeping) { return "sleeping"; }
    if (chomping || reactionType === "fed_meal" || reactionType === "fed_snack") { return "eating"; }
    if (state.sick) { return null; }
    return (state.mood === "happy" || state.mood === "sad") ? state.mood : null;
  }

  function moodFrame(mood, animTick) {
    var b = MOOD_BURSTS[mood];
    if (b) {
      var t = (animTick + b.offset) % b.every;
      return t < b.len ? 1 + Math.floor(t / b.ticks) % 2 : 0;
    }
    var f = MOOD_FRAMES[mood];
    return f ? Math.floor(animTick / f.ticks) % f.n : 0;
  }

  /** Vertical body squash / stretch for a mood frame, anchored at the feet (1 = none). */
  function moodScaleY(mood, frame) {
    if (mood === "happy")    { return frame === 1 ? 1.04 : 1; }   // two pulses per burst
    if (mood === "sad")      { return 0.95; }
    if (mood === "sleeping") { return 0.88; }
    if (mood === "eating")   { return [1, 0.92, 1.04][frame] || 1; }
    return 1;
  }

  /** Pixel size for mood props and particles, scaled with the pet. */
  // box.pxW (optional) overrides the width used for sizing — the classic creature
  // is narrower than its grid peers but keeps grid-sized props and particles.
  function moodPx(box) { return Math.max(1, Math.round((box.pxW || box.w) / 16)); }

  /**
   * Food bowl for a meal, drawn behind the pet. Snacks and other moods have no
   * props. box = {x, y, w, h} of the drawn pet, with y + h at the feet.
   */
  function drawMoodProps(ctx, mood, frame, box, facingLeft, snack) {
    if (mood !== "eating" || snack) { return; }
    var px = moodPx(box);
    var feetY = box.y + box.h;
    var bw = 6 * px;
    var bx = facingLeft ? box.x - bw - px : box.x + box.w + px;
    ctx.save();
    // Bowl, food level 2 → 1 → 0 across the chomp
    var fill = 2 - frame;
    if (fill > 0) {
      ctx.fillStyle = "#c8843c";
      ctx.fillRect(bx + px, feetY - (3 + fill) * px + px, bw - 2 * px, fill * px);
    }
    ctx.fillStyle = "#5b8fd9";
    ctx.fillRect(bx, feetY - 3 * px, bw, px);
    ctx.fillRect(bx + px, feetY - 2 * px, bw - 2 * px, px);
    ctx.fillStyle = "#3d6bb0";
    ctx.fillRect(bx + px, feetY - px, bw - 2 * px, px);
    ctx.restore();
  }

  /**
   * Add new particles for this frame. rand is injectable for tests.
   * frameChanged is true on the first tick of a new flip-book frame.
   */
  function spawnMoodParticles(particles, mood, frame, frameChanged, box, facingLeft, dt, rand) {
    rand = rand || Math.random;
    var headX = facingLeft ? box.x + box.w * 0.2 : box.x + box.w * 0.8;
    var add = [];
    if (mood === "happy" && frameChanged && frame === 1) {
      // 1–2 sparkles per stretch pulse → 2–4 per burst
      var sparkles = 1 + (rand() < 0.5 ? 1 : 0);
      for (var s = 0; s < sparkles; s++) {
        add.push({ kind: "sparkle", x: box.x + rand() * box.w, y: box.y + rand() * box.h * 0.3,
                   vx: 0, vy: -10, life: 0.6 });
      }
    } else if (mood === "sad" && frameChanged && frame > 0) {
      // One tear per burst frame → 3 per burst
      add.push({ kind: "tear", x: headX, y: box.y + box.h * 0.35, vx: 0, vy: 0, life: 2 });
    } else if (mood === "eating" && frameChanged && frame === 1) {
      var mouthX = facingLeft ? box.x : box.x + box.w;
      var count = 2 + (rand() < 0.5 ? 1 : 0);
      for (var i = 0; i < count; i++) {
        add.push({ kind: "crumb", x: mouthX, y: box.y + box.h * 0.45,
                   vx: (rand() - 0.5) * 40, vy: -20, life: 1.5 });
      }
    } else if (mood === "sleeping" && rand() < dt / 1.8) {
      add.push({ kind: "z", x: box.x + box.w * 0.6, y: box.y - 4, vx: 6, vy: -8, life: 2 });
    }
    for (var j = 0; j < add.length && particles.length < MOOD_PARTICLE_MAX; j++) {
      add[j].age = 0;
      particles.push(add[j]);
    }
  }

  /** Move particles and drop the ones that have faded or hit the floor. */
  function stepMoodParticles(particles, dt, floorY) {
    for (var i = particles.length - 1; i >= 0; i--) {
      var p = particles[i];
      p.age += dt;
      if (p.kind === "tear" || p.kind === "crumb") { p.vy += MOOD_GRAVITY * dt; }
      p.x += p.vx * dt;
      p.y += p.vy * dt;
      var falls = (p.kind === "tear" || p.kind === "crumb");
      if (p.age >= p.life || (falls && p.y >= floorY)) { particles.splice(i, 1); }
    }
  }

  function drawMoodParticles(ctx, particles, px) {
    ctx.save();
    for (var i = 0; i < particles.length; i++) {
      var p = particles[i];
      var x = Math.round(p.x), y = Math.round(p.y);
      ctx.globalAlpha = Math.max(0, 1 - p.age / p.life);
      if (p.kind === "sparkle") {
        ctx.fillStyle = "#fff4a3";
        ctx.fillRect(x - px, y, 3 * px, px);
        ctx.fillRect(x, y - px, px, 3 * px);
      } else if (p.kind === "tear") {
        ctx.fillStyle = "#7fb8ff";
        ctx.fillRect(x, y, px, 2 * px);
      } else if (p.kind === "crumb") {
        ctx.fillStyle = "#a0662a";
        ctx.fillRect(x, y, px, px);
      } else if (p.kind === "z") {
        ctx.fillStyle = "#c8c8ff";
        ctx.font = "bold 8px monospace";
        ctx.fillText("z", x, y);
      } else if (p.kind === "heart") {
        ctx.fillStyle = "#ff5c8a";
        ctx.fillRect(x - px, y, px, px);
        ctx.fillRect(x + px, y, px, px);
        ctx.fillRect(x - px, y + px, 3 * px, px);
        ctx.fillRect(x, y + 2 * px, px, px);
      } else if (p.kind === "prr") {
        ctx.fillStyle = "#ffd59a";
        ctx.font = "bold 7px monospace";
        ctx.fillText("prr", x, y);
      } else if (p.kind === "puff" || p.kind === "dust") {
        var grow = 1 + Math.floor(2 * p.age / p.life);
        ctx.fillStyle = p.kind === "dust" ? "#c8b090" : "#b8b8b8";
        ctx.fillRect(x, y, grow * px, grow * px);
      } else if (p.kind === "sticker") {
        ctx.fillStyle = p.colour || "#ffd54a";
        ctx.fillRect(x, y, 2 * px, 2 * px);
        ctx.fillStyle = "#ffffff";                    // peel-corner shine
        ctx.fillRect(x, y, px, px);
      }
    }
    ctx.restore();
  }

  /** Name of an optional per-mood grid for this stage, or null. */
  function moodGridKey(typeGrids, stage, mood) {
    if (!typeGrids || !mood) { return null; }
    var key = stage + "_" + mood;
    return typeGrids[key] ? key : null;
  }

  // =========================================================================
  // Pat reaction — per-pet body motion, a patting hand and floating hearts
  // =========================================================================

  var PAT_PARTICLE_MAX = 24;

  // Body motion for t in [0, 1]: {dx, dy, sx, sy, rot}, anchored at the feet.
  // Every motion is the identity at t = 0 and t = 1.
  function patEnv(t) { return Math.sin(t * Math.PI); }
  var PAT_MOTION = {
    // Tail-wag wiggle with two small hops
    dog: function (t) {
      var w = Math.sin(t * Math.PI * 8) * patEnv(t);
      return { dx: w * 2, dy: -Math.abs(Math.sin(t * Math.PI * 2)) * 6, sx: 1, sy: 1, rot: w * 0.06 };
    },
    // Arch up (stretch) then settle (squash)
    cat: function (t) {
      var a = Math.sin(t * Math.PI * 2);
      return { dx: 0, dy: 0, sx: 1 - a * 0.04, sy: 1 + a * 0.08, rot: 0 };
    },
    // Fleece puffs out
    sheep: function (t) {
      var e = patEnv(t);
      return { dx: 0, dy: 0, sx: 1 + e * 0.12, sy: 1 + e * 0.06, rot: 0 };
    },
    // Coils down and sways side to side
    snake: function (t) {
      var e = patEnv(t);
      return { dx: Math.sin(t * Math.PI * 6) * 4 * e, dy: 0, sx: 1 + e * 0.05, sy: 1 - e * 0.1, rot: 0 };
    },
    // Two little hops
    kangaroo: function (t) {
      return { dx: 0, dy: -Math.abs(Math.sin(t * Math.PI * 2)) * 10, sx: 1, sy: 1, rot: 0 };
    },
    // Happy loop in the air
    dragon: function (t) {
      var a = t * Math.PI * 2;
      return { dx: Math.sin(a) * 6, dy: (Math.cos(a) - 1) * 5, sx: 1, sy: 1, rot: Math.sin(a) * 0.15 };
    },
    // Tim's "Go for a Run": sidebar.js moves him round a lap (patRunLap);
    // here just a quick stride bob and a forward lean
    tim: function (t) {
      var e = patEnv(t);
      return { dx: 0, dy: -Math.abs(Math.sin(t * Math.PI * 14)) * 2 * e, sx: 1, sy: 1, rot: 0.06 * e };
    },
    // Stu's stickers: settles in over the binder / pack, small hop at the reveal
    stu: function (t) {
      var e = patEnv(t);
      var hop = (t > 0.4 && t < 0.6) ? Math.sin((t - 0.4) / 0.2 * Math.PI) : 0;
      return { dx: 0, dy: -hop * 6, sx: 1, sy: 1 - e * 0.03, rot: 0 };
    },
    // Squish twice
    classic: function (t) {
      var q = Math.abs(Math.sin(t * Math.PI * 2));
      return { dx: 0, dy: 0, sx: 1 + q * 0.08, sy: 1 - q * 0.15, rot: 0 };
    },
  };
  PAT_MOTION.roo = PAT_MOTION.kangaroo;

  // Custom characters whose "pat" is something else: Tim jogs a lap, Stu opens
  // a sticker binder or a pack of stickers. Neither gets the hand or hearts.
  var PAT_RUN   = { tim: 1 };
  var PAT_PROPS = { stu: ["binder", "pack"] };
  /** Reaction length (ms) for pets whose action needs longer than a pat. */
  var PAT_DURATION_MS = { tim: 2600, stu: 2200 };

  function patDurationMs(spriteType, fallback) { return PAT_DURATION_MS[spriteType] || fallback; }
  function patUsesHand(spriteType) { return !PAT_RUN[spriteType] && !PAT_PROPS[spriteType]; }

  /**
   * Lap position for a jogging pet: 0 at the start, 1 at the far end, back to 0;
   * null for pets that don't run. Eased so the turn-around slows down.
   */
  function patRunLap(spriteType, t) {
    if (!PAT_RUN[spriteType]) { return null; }
    return 0.5 - 0.5 * Math.cos(2 * Math.PI * Math.max(0, Math.min(1, t)));
  }

  /** Which prop this pet's action uses ("binder" / "pack"), picked at random; null if none. */
  function patPickProp(spriteType, rand) {
    var props = PAT_PROPS[spriteType];
    if (!props) { return null; }
    return props[Math.floor((rand || Math.random)() * props.length)];
  }

  var STICKER_COLOURS = ["#ff5c8a", "#4fc3f7", "#ffd54a", "#7ed957", "#b388ff", "#ff9e40"];
  /** Where a prop is held: in front of the torso, as {cx, cy}. */
  function patPropAnchor(box) {
    return { cx: box.x + box.w / 2, cy: box.y + box.h * 0.6 };
  }

  /**
   * Stu's sticker prop, held in front of the torso. "binder": a red ring binder
   * that opens onto pages of stickers. "pack": a foil pack whose top tears off.
   */
  function drawPatProp(ctx, variant, t, box, px) {
    if (!variant) { return; }
    var a = patPropAnchor(box);
    var u = Math.max(1, Math.round(px * 0.75));        // prop pixel
    function cell(cx, cy, cw, ch, colour) {
      ctx.fillStyle = colour;
      ctx.fillRect(Math.round(a.cx + cx * u), Math.round(a.cy + cy * u), cw * u, ch * u);
    }
    ctx.save();
    ctx.globalAlpha = Math.min(1, Math.min(t, 1 - t) * 10);
    if (variant === "binder") {
      var open = Math.max(0, Math.min(1, (t - 0.15) / 0.3));   // 0 closed → 1 open
      if (open < 0.5) {
        cell(-3, -4, 6, 8, "#8b1e3f");                 // closed cover
        cell(-3, -4, 1, 8, "#5c1229");                 // spine
        cell(-1, -1, 3, 2, "#ffd54a");                 // label
      } else {
        cell(-6, -4, 12, 8, "#8b1e3f");                // open covers
        cell(-5, -3, 10, 6, "#f2efe6");                // pages
        cell(0, -4, 1, 8, "#5c1229");                  // rings / spine
        for (var s = 0; s < 6; s++) {                  // sticker slots
          var sx = s < 3 ? -5 + s * 2 : 1 + (s - 3) * 2;
          cell(sx, -2, 1, 1, STICKER_COLOURS[s]);
          cell(sx, 1, 1, 1, STICKER_COLOURS[(s + 3) % STICKER_COLOURS.length]);
        }
      }
    } else {
      var torn = Math.max(0, Math.min(1, (t - 0.25) / 0.2));   // 0 sealed → 1 torn
      cell(-3, -2, 6, 7, "#c0c0d0");                   // foil body
      cell(-3, 0, 6, 1, "#e05252");                    // stripe
      cell(-1, 2, 2, 2, "#ffd54a");                    // star logo
      var lift = Math.round(torn * 4);                 // torn-off top flies up
      cell(-3 + (torn > 0 ? 1 : 0), -4 - lift, 6, 2, "#9a9ab0");
      if (torn >= 1) { cell(-2, -3, 4, 1, STICKER_COLOURS[0]); }   // stickers peeking out
    }
    ctx.restore();
  }

  function patMotion(spriteType, t) {
    var fn = PAT_MOTION[spriteType] || PAT_MOTION.classic;
    return fn(Math.max(0, Math.min(1, t)));
  }

  // Head position of the drawn pet: upright pets have it in the middle,
  // four-legged pets on the side they face.
  function patHeadX(box, facingLeft) {
    if (box.h > box.w) { return box.x + box.w * 0.5; }
    return facingLeft ? box.x + box.w * 0.2 : box.x + box.w * 0.8;
  }

  /** How far the hand is pressed onto the head (0..1); two pats per reaction. */
  function patDrop(t) { return Math.sin(((t * 2) % 1) * Math.PI); }

  /** Scale of the pat hand relative to the mood prop-pixel size. */
  var PAT_HAND_SCALE = 0.5;

  /** A sleeved hand above the head that pats down twice. */
  function drawPatHand(ctx, t, box, facingLeft, px) {
    var hp = px * PAT_HAND_SCALE;                    // hand pixel — half a prop-pixel
    var hx = patHeadX(box, facingLeft) - 3.5 * hp;
    var tipY = box.y + hp - (1 - patDrop(t)) * 5 * hp;   // fingertips
    // Cells in hand-pixel units, snapped to whole canvas pixels
    function cell(cx, cy, cw, ch) {
      var x0 = Math.round(hx + cx * hp), y0 = Math.round(tipY + cy * hp);
      ctx.fillRect(x0, y0, Math.max(1, Math.round(hx + (cx + cw) * hp) - x0),
                           Math.max(1, Math.round(tipY + (cy + ch) * hp) - y0));
    }
    ctx.save();
    ctx.globalAlpha = Math.min(1, Math.min(t, 1 - t) * 10);
    ctx.fillStyle = "#4a90d9";                       // sleeve cuff
    cell(0, -7, 7, 2);
    ctx.fillStyle = "#f5c5a3";                       // palm
    cell(0, -5, 7, 3);
    for (var f = 0; f < 4; f++) {                    // fingers
      cell(f * 2, -2, 1, 2);
    }
    ctx.fillStyle = "#d9a07c";                       // palm shading
    cell(0, -3, 7, 1);
    ctx.restore();
  }

  /** Cheek blush for the human characters, drawn inside the body transform. */
  function drawPatBlush(ctx, spriteType, t, box, px) {
    if (spriteType !== "tim" && spriteType !== "stu") { return; }
    var cx = box.x + box.w / 2, cy = Math.round(box.y + box.h * 0.22);
    ctx.save();
    ctx.globalAlpha = 0.7 * patEnv(t);
    ctx.fillStyle = "#ff8fa3";
    ctx.fillRect(Math.round(cx - box.w * 0.22) - px, cy, 2 * px, px);
    ctx.fillRect(Math.round(cx + box.w * 0.22) - px, cy, 2 * px, px);
    ctx.restore();
  }

  /**
   * Hearts for every pet, plus "prr" for the cat and smoke for the dragon.
   * Tim kicks up dust behind his feet; Stu's stickers burst out of the opened
   * binder / pack (t = reaction progress 0..1).
   */
  function spawnPatParticles(particles, spriteType, box, facingLeft, dt, rand, t) {
    rand = rand || Math.random;
    var headX = patHeadX(box, facingLeft);
    var add = [];
    if (PAT_RUN[spriteType] && rand() < dt * 10) {
      add.push({ kind: "dust", x: facingLeft ? box.x + box.w * 0.7 : box.x + box.w * 0.3, y: box.y + box.h - 2,
                 vx: (facingLeft ? 1 : -1) * (8 + rand() * 6), vy: -4, life: 0.5 });
    }
    if (PAT_PROPS[spriteType] && t !== undefined && t > 0.45 && t < 0.85 && rand() < dt * 12) {
      var a = patPropAnchor(box);
      add.push({ kind: "sticker", x: a.cx + (rand() - 0.5) * box.w * 0.3, y: a.cy - box.h * 0.1,
                 vx: (rand() - 0.5) * 30, vy: -22 - rand() * 10, life: 1,
                 colour: STICKER_COLOURS[Math.floor(rand() * STICKER_COLOURS.length)] });
    }
    if (patUsesHand(spriteType) && rand() < dt * 4) {
      add.push({ kind: "heart", x: headX + (rand() - 0.5) * box.w * 0.6, y: box.y,
                 vx: (rand() - 0.5) * 8, vy: -18, life: 1.1 });
    }
    if (spriteType === "cat" && rand() < dt * 1.5) {
      add.push({ kind: "prr", x: headX + (facingLeft ? -12 : 4), y: box.y + box.h * 0.3,
                 vx: facingLeft ? -6 : 6, vy: -6, life: 1 });
    }
    if (spriteType === "dragon" && rand() < dt * 3) {
      add.push({ kind: "puff", x: facingLeft ? box.x : box.x + box.w, y: box.y + box.h * 0.3,
                 vx: (facingLeft ? -1 : 1) * (10 + rand() * 8), vy: -6, life: 0.9 });
    }
    for (var j = 0; j < add.length && particles.length < PAT_PARTICLE_MAX; j++) {
      add[j].age = 0;
      particles.push(add[j]);
    }
  }

